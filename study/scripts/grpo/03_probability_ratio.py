"""概念三：概率比是什么意思，为什么每一步都要先保存一份权重。

模型在采样时，对某个词元给出过一个概率；训练时，当前模型对同一个词元给出另一个概率。
两者相除，就是「现在比当时更想要它，还是更不想要它」。

这个脚本用几组手算的数字把这个比值走一遍，顺便说明：
如果把采样时的概率覆盖成当前概率，比值会永远等于 1，训练就白做了。
"""

import math


def show(采样时概率, 当前概率, 说明):
    ratio = 当前概率 / 采样时概率
    # 代码里存的是对数概率，相减再取指数，等价于上面的除法。
    ratio_用对数实现 = math.exp(math.log(当前概率) - math.log(采样时概率))
    print(f"\n{说明}")
    print(f"  采样时的概率：{采样时概率:.2f}")
    print(f"  当前的概率：  {当前概率:.2f}")
    print(f"  概率比：      {ratio:.2f}（换成对数概率算也是 {ratio_用对数实现:.2f}）")


def main():
    show(0.10, 0.50, "现在比采样时更喜欢这个词：比值大于 1")
    show(0.50, 0.10, "现在比采样时更不喜欢它：比值小于 1")
    show(0.50, 0.50, "如果把历史记录覆盖成当前值：比值变成 1，训练信号就消失了")

    print("\n所以代码里存了两份对数概率：")
    print("  一份是采样那一刻的历史记录，跟着回答一起保存；")
    print("  一份是训练时重新算的当前值。")
    print("如果只剩当前值，就没法回答「当时有多想要它」，概率比也就失去了意义。")

    print("\n这也是每一步都要先保存权重、再采样的原因：")
    print("  保存下来的那份权重就是「当时」的模型，它给出的概率才是可信的参照。")


if __name__ == "__main__":
    main()
